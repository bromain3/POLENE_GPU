def _sample_indices(indicator: np.ndarray, n: int, rng: np.random.Generator) -> np.ndarray:
    weights = np.maximum(indicator, 0.0).astype(np.float64)
    total = weights.sum()
    if total == 0.0:
        raise ValueError("La somme des indicateurs est nulle.")
    return rng.choice(len(indicator), size=n, replace=True, p=weights / total)


class _GPUIntegrator:
    """Wrapper minimal autour de kineticsGPU pour intégrer des états TPY par batch."""

    def __init__(self, yaml_file: str, device: torch.device, dtype: torch.dtype,
                 newton_tol=1e-12, newton_maxiter=200,
                 gmres_restart=20, gmres_tol=1e-12, gmres_maxiter=50):
        self.device = device
        self.dtype = dtype
        self.np_dtype = np.float64 if dtype == torch.float64 else np.float32

        numba_cuda.select_device(device.index or 0)

        y = yamlParser(yaml_file)
        vec_th = y.populateVectorizedThermoObject(dtype=dtype, device=str(device))
        rxns = parseReactions(yaml_file)
        r_e, r_tb, r_f, _ = build_reactions(vec_th.species, rxns, vec_th, str(device), dtype)
        self.mech = build_mechanism_data_from_torch(r_e, r_tb, r_f, vec_th, dtype=self.np_dtype)

        self.n_species = self.mech.n_species
        self._newton_tol = newton_tol
        self._newton_maxiter = newton_maxiter
        self._gmres_restart = gmres_restart
        self._gmres_tol = gmres_tol
        self._gmres_maxiter = gmres_maxiter

        W_np = np.asarray(self.mech.thermo.molar_masses, dtype=self.np_dtype)
        self.W = torch.tensor(W_np, dtype=dtype, device=device)  # (n_sp,) kg/mol

    def _make_integrator(self, n: int) -> CUDABackwardEulerIntegratorPB:
        return CUDABackwardEulerIntegratorPB(
            mechanism=self.mech, n_reactors=n,
            newton_tol=self._newton_tol, newton_maxiter=self._newton_maxiter,
            gmres_restart=self._gmres_restart, gmres_tol=self._gmres_tol,
            gmres_maxiter=self._gmres_maxiter, dtype=self.np_dtype,
        )

    def integrate(self, states: np.ndarray, dt, n_substeps: int = 3) -> np.ndarray:
        """
        Intègre un batch d'états sur dt secondes avec substepping.

        Paramètres
        ----------
        states : np.ndarray, shape (B, 2 + n_species)
            Colonnes : [T (K), P (Pa), Y_1, ..., Y_K]

        dt : float ou np.ndarray shape (B,)
            Pas de temps total.

        n_substeps : int
            Nombre de sous-pas.

        Retour
        ------
        np.ndarray, shape (B, 2 + n_species)
        """
        #TODO: the substeping mechanism seems mandatory to generate a fine enough database that captures fast dynamics of trac species. It should be interesting to have this mechanism implemented in the integrator as it is for cantera
        # The way the integrate function is defined copies exactly how the database is generated by NeuralCFD for maximum coherence.
        B = states.shape[0]

        T = torch.tensor(states[:, 0], dtype=self.dtype, device=self.device)
        P = torch.tensor(states[:, 1], dtype=self.dtype, device=self.device)
        Ys = torch.tensor(states[:, 2:], dtype=self.dtype, device=self.device)

        # Normalisation sécurité
        Ys = torch.clamp(Ys, min=0.0)
        Ys = Ys / Ys.sum(dim=1, keepdim=True).clamp(min=1e-30)

        # Masse molaire moyenne → densité
        R_u = 8.314_462_618_153_24
        W_mix = 1.0 / (Ys / self.W.unsqueeze(0)).sum(dim=1)
        rho = P * W_mix / (R_u * T)

        # Concentrations
        C = rho.unsqueeze(1) * Ys / self.W.unsqueeze(0)

        # Buffer TC
        TC = torch.zeros((B, self.n_species + 1),
                         dtype=self.dtype,
                         device=self.device)

        TC[:, 0] = T
        TC[:, 1:] = C

        integrator = self._make_integrator(B)

        def _step(TC_buf, h_vec):
            d_TC = numba_cuda.as_cuda_array(TC_buf)

            d_TC, d_conv = integrator.step(d_TC, h=h_vec)

            result = torch.as_tensor(d_TC, device=self.device)
            converged = torch.as_tensor(d_conv, device=self.device)

            if result.data_ptr() != TC_buf.data_ptr():
                TC_buf.copy_(result)

            return TC_buf, converged

        # ------------------------------------------------------------------ #
        # Construction des sous-pas
        # ------------------------------------------------------------------ #

        if np.isscalar(dt):
            dt_array = np.full(B, dt, dtype=np.float64)
        else:
            dt_array = np.asarray(dt, dtype=np.float64)

        h_sub = dt_array / n_substeps

        # ------------------------------------------------------------------ #
        # Boucle de substepping
        # ------------------------------------------------------------------ #

        for _ in range(n_substeps):

            TC_before = TC.clone()

            TC, conv = _step(TC, h_sub)

            failed = (conv != 1)

            if failed.any():
                raise ValueError(
                    f"Réacteurs non convergés : "
                    f"{failed.nonzero().flatten()}"
                )
                # rollback
                TC[failed] = TC_before[failed]

                # demi-pas
                h_half = np.where(
                    failed.cpu().numpy(),
                    h_sub / 2,
                    0.0
                )

                TC, conv2 = _step(TC, h_half)
                TC, conv2 = _step(TC, h_half)

                still_failed = (conv2 != 1) & failed

                if still_failed.any():
                    raise ValueError(
                        f"Réacteurs non convergés : "
                        f"{still_failed.nonzero().flatten()}"
                    )

        # ------------------------------------------------------------------ #
        # Reconstruction TPY
        # ------------------------------------------------------------------ #

        T_new = TC[:, 0]
        C_new = TC[:, 1:]

        mass_new = C_new * self.W.unsqueeze(0)

        rho_new = mass_new.sum(dim=1, keepdim=True)

        Ys_new = mass_new / rho_new.clamp(min=1e-30)

        R_spec = (Ys_new / self.W.unsqueeze(0)).sum(dim=1) * R_u

        P_new = rho_new.squeeze(1) * R_spec * T_new

        out = torch.cat([
            T_new.unsqueeze(1),
            P_new.unsqueeze(1),
            Ys_new
        ], dim=1)

        return out.cpu().numpy()


def generateInitialConditionSamples(sampligMethode, nTrajectories):
    samplingRange = {'T': [1600, 1800], 'P': 101325, 'phi': [0.7, 1.5]}
    hypercubeSize = len(samplingRange)

    # checking if the variable is constant or not (for pressure for instance)
    const = []
    for var, r in samplingRange.items():
        const.append(not isinstance(r, (list, tuple, np.ndarray)))

    # Pseudo random engine generation and samples generation only for variables that are not constant
    sampler = getattr(qmc, sampligMethode)(d=const.count(False))
    sample = sampler.random(n=nTrajectories)

    # scaling samples
    l_bound = []
    u_bound = []
    for var, r in samplingRange.items():
        if isinstance(r, (list, tuple, np.ndarray)):
            l_bound.append(min(r))
            u_bound.append(max(r))

    sample = qmc.scale(sample, l_bound, u_bound)

    # reconstructing the full sample table
    res = np.zeros((nTrajectories, hypercubeSize))
    usedSamplingCols = 0
    for i in range(hypercubeSize):
        if const[i]:
            val = list(samplingRange.values())[i]
            res[:, i] = val
        else:
            res[:, i] = sample[:, usedSamplingCols]
            usedSamplingCols += 1

    res = np.array(res) # serie(res, list(self.samplingRange.keys()), storingDevice=self.storingDevice, storingDtype=self.storingDtype)
    return res

def cstV(
    initialConditionsNumber,
    colNames,
    dt: float,
    tend,
    kinetics: str,
    samplingMethod: str = "Halton",
    n_substeps: int = 1,
    batch_size: int = 10000,
    device: torch.device | str = "cuda:0",
    dtype: torch.dtype = torch.float64,
    **integrator_kwargs,
):
    device = torch.device(device)
    gpu = _GPUIntegrator(kinetics, device, dtype, **integrator_kwargs)

    n_steps = int(round(tend / dt))
    N = initialConditionsNumber

    # Génération des conditions initiales
    initialConditions = generateInitialConditionSamples(samplingMethod, N)
    # initialConditions : (N, 3) — colonnes [T, P, phi]
    ic_col = ['T', 'P', 'phi']
    nStates = len(colNames)
    total = N * n_steps
    X_all = np.empty((total, nStates), dtype=np.float64)
    Y_all = np.empty((total, nStates), dtype=np.float64)
    tX_all = np.empty(total, dtype=np.float64)
    tY_all = np.empty(total, dtype=np.float64)

    def phi2Y(phi):
        MMCH4 = 16.04
        MMO2  = 31.999
        O2_N2 = 3.32
        mch4_mo2_st = MMCH4 / (2 * MMO2)
        buff_ch4 = phi * mch4_mo2_st * 2 * MMO2
        buff_o2  = np.full_like(phi, 2 * MMO2)
        buff_n2  = np.full_like(phi, 2 * MMO2 * O2_N2)
        total_mass = buff_ch4 + buff_o2 + buff_n2
        Y = np.zeros((len(phi), nStates - 2), dtype=np.float64)
        Y[:, colNames.index('CH4') - 2] = buff_ch4 / total_mass
        Y[:, colNames.index('O2') - 2]  = buff_o2  / total_mass
        Y[:, colNames.index('N2') - 2]  = buff_n2  / total_mass
        return Y

    # Construction de l'état initial [T, P, Y_1, ..., Y_K]
    states_init = np.zeros((N, nStates), dtype=np.float64)
    states_init[:, 0] = initialConditions[:, ic_col.index('T')]
    states_init[:, 1] = initialConditions[:, ic_col.index('P')]
    states_init[:, 2:] = phi2Y(initialConditions[:, ic_col.index('phi')])

    states_current = states_init.copy()

    for step in tqdm(range(n_steps), desc="cstV integration"):
        states_next = np.empty_like(states_current)

        for start in range(0, N, batch_size):
            end = min(start + batch_size, N)
            states_next[start:end] = gpu.integrate(
                states_current[start:end], dt, n_substeps=n_substeps
            )

        offset = step * N
        X_all[offset:offset + N] = states_current
        Y_all[offset:offset + N] = states_next
        tX_all[offset:offset + N] = step * dt
        tY_all[offset:offset + N] = (step + 1) * dt

        states_current = states_next

    X_out = serie(X_all, colNames, storingDevice="cpu", storingDtype=torch.float64)
    Y_out = serie(Y_all, colNames, storingDevice="cpu", storingDtype=torch.float64)
    tX_out = serie(tX_all.reshape(-1, 1), ['t'], storingDevice="cpu", storingDtype=torch.float64)
    tY_out = serie(tY_all.reshape(-1, 1), ['t'], storingDevice="cpu", storingDtype=torch.float64)
    return X_out, Y_out, tX_out, tY_out
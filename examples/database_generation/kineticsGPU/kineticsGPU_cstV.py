import POLENE_GPU.databaseGeneration.standalone.kinteicsGPU0D as kin
import POLENE_GPU.databaseGeneration.models.cantera0D as cantera0D
import POLENE_GPU.databaseGeneration.databaseGenerator as databaseGenerator
from POLENE_GPU.misc.timer import Timer

import torch
import matplotlib.pyplot as plt

device = torch.device('cuda:0')
dtype = torch.float64
CPUparallelProcessing = 5  # False or number of processor used

n_init_cond = 100

model = cantera0D.cstP(
    kinetics='gri30.yaml',
    dtcfd=1e-6,
    tmax=1e-2,
    equilibriumTolerance=1e-10,
    samplingRange={'T': [1699, 1701], 'P': 101325.0, 'phi': [0.99, 1.01]},
    cstSamplingdt=False,
)

with Timer("DatabaseGenerator creation"):
    dtbgen = databaseGenerator.DatabaseGenerator(model, storingDevice=device, storingDtype=dtype)

with Timer("Single trajectory"):
    X, Y, tX, tY = dtbgen.generateSingleTrajectory({'T': 1350, 'P': 101325, 'phi': 1.0})  # outputs series if generated by dbgen, outputs np.array otherwise

with Timer("Model creation"):
    X_gpu, Y_gpu, tX_gpu, tY_gpu = kin.cstV(1, X.colName, 1e-6, 1e-3, 'gri30.yaml', n_substeps=5)

with Timer("Model creation"):
    Xdtb, Ydtb, tXdtb, tYdtb = kin.cstV(n_init_cond, X.colName, 1e-6, 1e-3, 'gri30.yaml', n_substeps=5)


plt.plot(tX_gpu['t'].cpu().detach().numpy(), X_gpu['T'].cpu().detach().numpy())
plt.show()

plt.plot(tX_gpu['t'].cpu().detach().numpy(), X_gpu['P'].cpu().detach().numpy())
plt.show()

plt.plot(tX_gpu['t'].cpu().detach().numpy(), X_gpu['C'].cpu().detach().numpy())
plt.show()

plt.hist(X_gpu['T'].cpu().detach().numpy(), bins=50)
plt.show()

plt.hist(Xdtb['T'].cpu().detach().numpy(), bins=50)
plt.show()